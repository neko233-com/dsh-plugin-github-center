// Isolated host/browser smoke; server token stays in memory, never in logs.
const { spawn, spawnSync, execFileSync } = require('node:child_process')
const { mkdtempSync } = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const http = require('node:http')
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const ps = process.env.DSH_TEST_PWSH || 'pwsh'
const env = {...process.env, DSH_HOME:mkdtempSync(path.join(os.tmpdir(),'dsh-community-ui-')), DSH_CENTER_PLUGIN_DIR:process.cwd()}
const install = spawnSync(ps, ['-NoProfile','-Command', "& dsh plugin --profile web add ('link:' + $env:DSH_CENTER_PLUGIN_DIR); exit $LASTEXITCODE"], {env,encoding:'utf8',windowsHide:true})
if (install.status !== 0) throw new Error(`Cannot install test bundle: ${install.stderr}`)
const host = spawn(ps, ['-NoProfile','-Command','& dsh --profile web --port 0 --no-open'], {env,windowsHide:true,stdio:['ignore','pipe','pipe']})
let hostErrors=''; host.stderr.on('data',data=>{hostErrors+=data})
const serverUrl = new Promise((resolve,reject)=>{
  let output=''; const timeout=setTimeout(()=>reject(new Error('Host start timed out')),45000)
  const onData=data=>{output+=data; const match=output.match(/http:\/\/127\.0\.0\.1:\d+\/\?token=[^\s]+/); if(match){clearTimeout(timeout);resolve(match[0])}}
  host.stdout.on('data',onData);host.stderr.on('data',onData);host.on('exit',code=>reject(new Error(`Host exited: ${code}`)))
})
;(async()=>{
  let browser, indexServer
  try {
    const entries=Array.from({length:120},(_,i)=>({name:`company-plugin-${String(i).padStart(3,'0')}`,description:i===119?'specialneedle':'Company plugin',versions:[{version:'1.0.0',publishTimestamp:1,source:{type:'npm'}}]}))
    indexServer=http.createServer((_req,res)=>{res.writeHead(200,{'content-type':'application/json'});res.end(JSON.stringify({format:1,title:'测试团队源',plugins:entries}))})
    await new Promise(resolve=>indexServer.listen(0,'127.0.0.1',resolve))
    browser=await chromium.launch({headless:true,channel:'chrome'})
    const page=await browser.newPage({viewport:{width:1400,height:900}})
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.goto(await serverUrl); await page.waitForTimeout(4000)
    const continueButton=page.getByRole('button',{name:'继续',exact:true})
    if(await continueButton.count()) await continueButton.click()
    await page.waitForTimeout(1200)
    const close=page.getByRole('button',{name:'关闭',exact:true})
    if(await close.count()) await close.last().click()
    await page.getByRole('button',{name:'插件',exact:true}).click()
    await page.waitForTimeout(2500)
    if(await close.count()) await close.last().click()
    await page.getByRole('switch',{name:'启用 自定义插件索引'}).click()
    await page.waitForTimeout(2500)
    await page.getByRole('tab',{name:'社区插件中心',exact:true}).click()
    await page.getByRole('heading',{name:'社区插件中心',exact:true}).waitFor()
    assert.equal(await page.locator('.ghc-card').count(),200)
    await page.getByLabel('搜索插件').fill('dshmarket')
    assert.equal(await page.locator('.ghc-card').count(),1)
    await page.getByLabel('选择安装 dshmarket').check()
    await page.getByLabel('搜索插件').fill('')
    await page.getByLabel('选择安装 dsh-whale-widget').check()
    assert.equal(await page.getByRole('button',{name:'安装所选 (2)'}).isEnabled(),true)
    let prompt=''; page.once('dialog',d=>{prompt=d.message();return d.dismiss()})
    await page.getByRole('button',{name:'安装所选 (2)'}).click()
    assert.match(prompt,/dshmarket/)
    assert.match(prompt,/dsh-whale-widget/)
    await page.screenshot({path:path.join(os.tmpdir(),'dsh-community-center.png')})
    await page.evaluate(()=>document.body.setAttribute('data-ds-dark-theme',''))
    const colors=await page.locator('.ghc-card').first().evaluate(e=>({bg:getComputedStyle(e).backgroundColor,color:getComputedStyle(e).color}))
    assert.notEqual(colors.bg,'rgb(255, 255, 255)')
    await page.screenshot({path:path.join(os.tmpdir(),'dsh-community-center-dark.png')})
    await page.evaluate(()=>document.body.removeAttribute('data-ds-dark-theme'))
    await page.getByRole('button',{name:'插件来源',exact:true}).click()
    if(await page.getByRole('button',{name:'添加来源',exact:true}).isDisabled()) await page.locator('.ghc-message').getByRole('button',{name:'刷新'}).click()
    await page.getByLabel('索引 URL').fill(`http://127.0.0.1:${indexServer.address().port}/index.json`)
    await page.getByRole('button',{name:'添加来源',exact:true}).click()
    try { await page.getByText('company-plugin-000',{exact:true}).first().waitFor({timeout:15000}) }
    catch(e) { console.error('INDEX VIEW:',(await page.locator('.ghc').innerText()).slice(0,1200)); console.error('HOST EXIT:',host.exitCode,'HOST ERRORS:',hostErrors.replace(/token=[^\s]+/g,'token=[redacted]').slice(-3000)); throw e }
    assert.equal(await page.locator('.ghc-card').count(),50)
    await page.getByRole('button',{name:'加载更多'}).click()
    await page.waitForFunction(()=>document.querySelectorAll('.ghc-card').length===100)
    await page.getByLabel('搜索插件').fill('specialneedle')
    await page.getByText('company-plugin-119',{exact:true}).first().waitFor()
    assert.equal(await page.locator('.ghc-card').count(),1)
    assert.deepEqual(errors,[])
    console.log('Host UI: community center, 200 cards, multi-select, confirmation, dark theme, custom index pagination/search and no page errors passed.')
    console.log('Screenshots:',path.join(os.tmpdir(),'dsh-community-center.png'),path.join(os.tmpdir(),'dsh-community-center-dark.png'))
  } finally {
    indexServer?.close()
    if(browser) await browser.close()
    try { execFileSync('taskkill',['/PID',String(host.pid),'/T','/F'],{stdio:'ignore'}) } catch {}
  }
})().catch(error=>{console.error(error.message); process.exitCode=1})
